def search_companies(keyword: str, limit: int = 15) -> list:
    """
    搜尋公司，支援代號或名稱的模糊搜尋

    Parameters
    ----------
    keyword : str
        搜尋關鍵字（代號或公司名稱）
    limit : int
        最多回傳幾筆結果

    Returns
    -------
    list of dict
        [{'code': '2330', 'name': '台積電'}, ...]
    """
    keyword = keyword.strip()
    if not keyword:
        return []

    exact_code = []
    starts_with_code = []
    partial_code = []
    name_match = []

    for code, name in COMPANY_DB.items():
        if code == keyword:
            exact_code.append({'code': code, 'name': name})
        elif code.startswith(keyword):
            starts_with_code.append({'code': code, 'name': name})
        elif keyword in code:
            partial_code.append({'code': code, 'name': name})
        elif keyword in name:
            name_match.append({'code': code, 'name': name})

    # 排序：代號精確 > 代號開頭 > 代號包含 > 名稱包含
    starts_with_code.sort(key=lambda x: x['code'])
    partial_code.sort(key=lambda x: x['code'])
    name_match.sort(key=lambda x: x['code'])

    results = exact_code + starts_with_code + partial_code + name_match
    return results[:limit]


def get_company_name(company_id: str) -> str:
    """根據公司代號取得名稱，找不到回傳空字串"""
    return COMPANY_DB.get(str(company_id).strip(), '')
